import * as React from "react";
import { cn } from "@/lib/utils";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverable?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverable = false, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "bg-white border border-[#e2e7e1] rounded-[12px] shadow-[0_1px_3px_0_rgba(0,0,0,0.04)] overflow-hidden",
        hoverable &&
          "transition-all duration-200 hover:shadow-md hover:border-[#15594f]/30 hover:-translate-y-0.5 cursor-pointer",
        className
      )}
      {...props}
    />
  )
);
Card.displayName = "Card";

